#五人分鱼
"""
A、B、C、D、E 五人在某天夜里合伙去捕鱼，到第二天凌晨时都疲惫不堪，于是各自找地方睡觉。

日上三杆，A 第一个醒来，他将鱼分为五份，把多余的一条鱼扔掉，拿走自己的一份。

B 第二个醒来，也将鱼分为五份，把多余的一条鱼扔掉拿走自己的一份。 。

C、D、E依次醒来，也按同样的方法拿鱼。

问他们至少捕了多少条鱼?
"""
#暴力解法
n = 1
while True:
    x = n
    flag = True
    for _ in range(5):
        if x % 5 != 1:
            flag = False
            break
        x = 4 * (x - 1) // 5
    if flag:
        print(f"鱼的总数是：{n}")
        break
    n += 1